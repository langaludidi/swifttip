# SwiftTip Worker Terms — Draft v0.1

**Status: DRAFT / NOT PUBLISHED / NOT IN FORCE**

This document is a pre-live drafting instrument for legal, commercial and payment-provider review. It must not be presented to Workers as operative terms until the SwiftTip legal-version workflow records an approved, published and effective version.

## 1. About these Terms

These Worker Terms govern a Worker’s use of SwiftTip to receive attributable digital gratuities from customers. In these Terms:

- **SwiftTip** means the digital gratuity platform operated by **[LEGAL ENTITY NAME TO BE CONFIRMED]**.
- **Worker** means an individual approved to use a verified SwiftTip Worker profile.
- **Venue** means the participating business or location with which the Worker has a verified working relationship.
- **Customer** means a person who chooses to send a gratuity through SwiftTip.
- **Payment Provider** means the regulated or otherwise appropriately authorised third-party payment service provider used to process payment and Settlement.
- **Gratuity** means the amount a Customer voluntarily designates for a Worker, before any disclosed Worker success fee.
- **Worker Success Fee** means the SwiftTip transaction fee applicable to a successful gratuity under the Pricing Version shown to the Worker before activation and in the relevant transaction record.
- **Worker Net Entitlement** means the Gratuity less the applicable Worker Success Fee.
- **Settlement** means the Payment Provider’s transfer or making available of the Worker Net Entitlement through the approved provider settlement arrangement.

## 2. What SwiftTip does

SwiftTip provides identity, Venue-association, customer-facing tipping, transaction-record and operational-support infrastructure intended to make digital gratuities attributable to a verified individual Worker.

SwiftTip is designed as a **non-custodial platform**. The intended live payment model is that the Payment Provider processes and allocates funds so that SwiftTip receives only the fees to which it is entitled and does not hold a Worker wallet or take custody of the Worker Net Entitlement.

The final live funds flow remains subject to written confirmation by the selected Payment Provider and legal review. SwiftTip must not activate a Worker for live payments if the approved provider arrangement materially differs from the non-custodial architecture without revised terms and controls.

## 3. SwiftTip does not employ the Worker

Using SwiftTip does not, by itself, create an employment, agency, partnership, joint venture or payroll relationship between the Worker and SwiftTip.

SwiftTip does not determine the Worker’s employment status, wages, working hours, duties, leave, disciplinary rules or other conditions of work at a Venue. Those matters remain between the Worker and the relevant employer, contractor, Venue or other lawful party.

A verified Venue association confirms only the relationship required for SwiftTip participation. It is not a declaration by SwiftTip concerning the Worker’s legal employment status.

## 4. Eligibility and activation

A Worker may receive live gratuities only while all activation requirements are satisfied. These may include:

1. a verified SwiftTip account and secure authentication;
2. completion of the Worker profile;
3. SwiftTip identity verification;
4. a current verified Venue association;
5. required Payment Provider onboarding, KYC and Settlement readiness;
6. acceptance of the current published Worker Terms; and
7. any other lawful risk or security control reasonably required for the service.

SwiftTip may keep a Worker profile in draft, pending or suspended status while a required control remains incomplete.

## 5. Worker identity and public profile

The Worker must provide accurate information and must not impersonate another person or create misleading Worker profiles.

SwiftTip may keep legal identity information private while showing a limited public profile to Customers. The intended public profile may include the Worker’s chosen first name, approved photograph, role, Venue and SwiftTip verification indicator.

Legal surnames, identity documents, phone numbers, Payment Provider KYC records and banking or Settlement details must not be exposed on the public tipping profile.

## 6. Venue relationship

The Worker may request an association with a participating Venue. The Venue must independently confirm that the Worker currently has the relevant relationship with that Venue.

A Worker must not claim a Venue at which the Worker does not currently work or otherwise lawfully provide the relevant service.

If the Worker leaves the Venue or the association otherwise ends, either the authorised Venue user or SwiftTip may end the association. Historical transaction records remain preserved.

Ending a Venue association does not automatically delete the Worker’s SwiftTip account, but it may make the Worker ineligible to receive new gratuities until another valid association is confirmed.

## 7. Gratuities and fees

Customers choose whether to tip and how much to tip, subject to SwiftTip’s configured minimum, maximum and risk controls.

SwiftTip does not guarantee that a Worker will receive any minimum number or value of gratuities.

SwiftTip is free for a Worker to join and remain on the platform unless a later published version expressly states otherwise. SwiftTip may earn a **Worker Success Fee only when the Worker earns through a successful gratuity transaction**, under the applicable approved Pricing Version.

Before Worker activation, SwiftTip must disclose the applicable Worker Success Fee. Each transaction record must show, at minimum:

- the gross Gratuity;
- the Worker Success Fee;
- the Worker Net Entitlement; and
- the relevant Payment/Settlement status.

No fee may be silently introduced or retroactively applied to a completed transaction.

## 8. Settlement is different from payment success

A Customer payment being confirmed does not necessarily mean the Worker’s Settlement has already completed.

SwiftTip may display statuses such as **Received**, **Processing**, **Settlement pending**, **Settled** or **Settlement exception**. SwiftTip will not describe a Worker amount as settled unless the canonical Payment Provider or reconciliation evidence supports that state.

The timing and method of Settlement will depend on the approved Payment Provider arrangement and the Worker’s valid settlement destination.

SwiftTip does not provide a stored-value wallet, cash-out balance or withdrawal facility in the MVP architecture.

## 9. Settlement destination and account security

A Worker must protect authentication credentials and promptly report suspected unauthorised access.

Changes to a Settlement destination are high-risk actions and may be subject to step-up authentication, Payment Provider verification, temporary holds, cooling-off controls or manual review.

SwiftTip may delay activation of a changed Settlement destination where reasonably necessary to protect the Worker or the integrity of the payment system.

## 10. Refunds, reversals, chargebacks and disputes

Customer payments may be subject to refunds, reversals, card disputes, chargebacks, fraud claims or other Payment Provider processes.

**The final allocation of loss where a chargeback or refund occurs after Worker Settlement is not yet approved and is a publication blocker for these Terms.** SwiftTip will not publish a final version that imposes an undisclosed Worker debt, negative wallet or automatic clawback mechanism.

Any final recovery right, reserve, set-off, delayed Settlement rule or loss-allocation rule affecting a Worker must be expressly stated in the published Worker Terms and supported by the approved provider/legal model.

## 11. Tax and personal financial obligations

Workers remain responsible for obtaining appropriate tax or financial advice concerning gratuities and any personal obligations arising from amounts received through SwiftTip.

SwiftTip will provide transaction records reasonably required to understand amounts processed through the platform. SwiftTip will not represent a tax treatment as settled until the relevant South African tax and accounting treatment has been confirmed for the final operating model.

## 12. Prohibited conduct

A Worker must not:

- use a false identity or another Worker’s profile;
- tamper with, copy or redirect another Worker’s QR code or short code;
- use SwiftTip for payments that are not genuine voluntary gratuities where the platform is presented as a tipping service;
- create sham, self-funded or collusive transactions to manufacture volume or revenue;
- attempt to bypass Payment Provider controls, security controls or fee disclosures;
- use SwiftTip for unlawful goods, services or conduct;
- harass Customers for gratuities or misrepresent that a tip is mandatory; or
- interfere with SwiftTip records, reconciliation or investigations.

## 13. Suspension and termination

SwiftTip may suspend a Worker profile where reasonably necessary for security, fraud prevention, verification, compliance, Venue-association integrity, Payment Provider requirements or investigation of a material breach.

Where practicable and lawful, SwiftTip will communicate the reason and the steps required to resolve the issue.

Termination does not erase completed transaction, Settlement, dispute, audit or compliance records that SwiftTip is lawfully required or reasonably entitled to retain.

## 14. Privacy

SwiftTip processes personal information in accordance with the applicable published SwiftTip Privacy Notice and South African data-protection requirements.

The Worker should review the Privacy Notice for the categories of information collected, purposes, recipients, retention principles, cross-border processing (if any), security measures and data-subject rights.

## 15. Electronic records and acceptance

SwiftTip may present these Terms electronically and record acceptance electronically. The platform records the specific version accepted, the time of acceptance and related evidence required for auditability.

The Worker must be able to review the exact published version before accepting it and must be able to access that version afterward.

## 16. Changes to these Terms

SwiftTip will not silently alter a published Terms version. A material change requires a new version.

Where re-acceptance is appropriate, SwiftTip may require the Worker to accept the new version before continuing to receive new gratuities.

## 17. Availability and service changes

SwiftTip may perform maintenance, security changes or service changes. SwiftTip does not guarantee uninterrupted availability.

If a material security or payment-integrity risk arises, SwiftTip may disable new payments through a platform kill switch while preserving existing records and reconciliation evidence.

## 18. Liability framework — draft position

SwiftTip is responsible for operating its platform with reasonable care and in accordance with applicable law, but it does not control the banking system, card schemes, a Customer’s issuer, the Payment Provider, a Venue’s employment practices or external communications networks.

Any final limitation-of-liability, indemnity or exclusion clause must be reviewed for enforceability under South African law and must not purport to exclude rights or liability that cannot lawfully be excluded.

## 19. Complaints and support

Workers may raise a support case through the SwiftTip Worker interface. SwiftTip will maintain an auditable case record for material operational issues.

Final external complaint/escalation channels will be inserted before publication once the SwiftTip legal entity, Payment Provider and regulatory responsibilities are confirmed.

## 20. Governing law

The intended governing law is the law of the Republic of South Africa, subject to mandatory rights and jurisdiction that cannot lawfully be excluded.

The final dispute-resolution clause and legal notices address must be confirmed before publication.

